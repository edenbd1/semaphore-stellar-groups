import { poseidon2 } from "poseidon-lite"
import { createRequire } from "module"
import { writeFileSync } from "fs"
const require = createRequire(import.meta.url)
const unstr = require("./node_modules/poseidon-lite/poseidon/unstringify.js")
const raw = require("./node_modules/poseidon-lite/constants/2.js")
const c = (unstr.default || unstr)(raw.default || raw)

const C = c.C.map((x) => BigInt(x))
const M = c.M.map((row) => row.map((x) => BigInt(x)))
const be32 = (d) => BigInt(d).toString(16).padStart(64, "0")
const arr = (hex) => "[" + hex.match(/../g).map((x) => "0x" + x).join(", ") + "]"
const u256 = (d) => arr(be32(d))

const L = [
    "// AUTO-GENERATED by tools/gen-poseidon-params.mjs — circomlib Poseidon (BN254, t=3).",
    "// 2-input hash as in circomlib / @zk-kit LeanIMT: state=[0,a,b], 8 full + 57 partial rounds.",
    "",
    "pub const ROUNDS_F: u32 = 8;",
    "pub const ROUNDS_P: u32 = 57;",
    "pub const D: u32 = 5;",
    "",
    "// round constants: (ROUNDS_F + ROUNDS_P) * 3 = 195, big-endian 32-byte",
    "pub const C: [[u8; 32]; 195] = [",
]
for (const x of C) L.push("    " + u256(x) + ",")
L.push("];", "", "pub const M: [[[u8; 32]; 3]; 3] = [")
for (const row of M) L.push("    [" + row.map((x) => u256(x)).join(", ") + "],")
L.push("];", "", "// test vectors: (a, b, poseidon2([a,b]))")
const tv = [[1n, 2n], [7n, 42n]]
L.push(`pub const TV: [([u8; 32], [u8; 32], [u8; 32]); ${tv.length}] = [`)
for (const [a, b] of tv) L.push("    (" + u256(a) + ", " + u256(b) + ", " + u256(poseidon2([a, b])) + "),")
L.push("];", "")

writeFileSync("/tmp/poseidon_params.rs", L.join("\n"))
console.log("OK | poseidon2([1,2]) =", poseidon2([1n, 2n]).toString())
console.log("    poseidon2([7,42]) =", poseidon2([7n, 42n]).toString())
