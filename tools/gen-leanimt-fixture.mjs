// Reference LeanIMT roots after each insertion (via @zk-kit, circomlib poseidon2), to test the
// on-chain tree matches @zk-kit / Semaphore Group exactly (odd & even sizes).
import { LeanIMT } from "@zk-kit/lean-imt"
import { poseidon2 } from "poseidon-lite"
import { writeFileSync } from "fs"
const be32 = (d) => BigInt(d).toString(16).padStart(64, "0")
const arr = (hex) => "[" + hex.match(/../g).map((x) => "0x" + x).join(", ") + "]"
const leaves = [1n, 2n, 3n, 4n, 5n]
const t = new LeanIMT((a, b) => poseidon2([a, b]))
const roots = []
for (const l of leaves) { t.insert(l); roots.push(t.root.toString()) }
const L = ["// AUTO-GENERATED by tools/gen-leanimt-fixture.mjs — @zk-kit LeanIMT reference roots.", ""]
L.push(`pub const LEAVES: [[u8; 32]; ${leaves.length}] = [`)
for (const l of leaves) L.push("    " + arr(be32(l)) + ",")
L.push("];", `pub const ROOT_AFTER: [[u8; 32]; ${roots.length}] = [`)
for (const r of roots) L.push("    " + arr(be32(r)) + ",")
L.push("];", "")
writeFileSync("/tmp/leanimt_fixture.rs", L.join("\n"))
console.log("roots after each insert:"); roots.forEach((r,i)=>console.log(` n=${i+1}:`, r.slice(0,24)+"…"))
